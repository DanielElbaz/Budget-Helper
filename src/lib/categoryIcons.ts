/** Icon key for a stored value: a key as-is, or the key a legacy emoji maps to. */
export function categoryIconKey(stored: string): string | undefined {
  if (stored in CATEGORY_ICONS) return stored
  return LEGACY_EMOJI[stored]
}

export function categoryIconFor(stored: string): LucideIcon | undefined {
  const key = categoryIconKey(stored)
  return key ? CATEGORY_ICONS[key].icon : undefined
}
